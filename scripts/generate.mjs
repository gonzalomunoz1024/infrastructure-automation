#!/usr/bin/env node
// Regenerates everything this branch derives from the pinned contract, openapi/console-bff.yaml:
//
//   packages/sdk/src/generated/console-bff.ts   the contract's types, by openapi-typescript
//   packages/sdk/src/generated/operations.ts    how to call each operation (method, path, parameters)
//   packages/cli-core/src/generated/commands.ts the CLI's command table, one command per operation
//
// `npm run generate` writes them; `npm run generate:check` (CI, and test/generated.test.mjs)
// fails when a committed file differs from what the contract gives.

import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const CONTRACT = 'openapi/console-bff.yaml';
export const OUTPUTS = {
  types: 'packages/sdk/src/generated/console-bff.ts',
  operations: 'packages/sdk/src/generated/operations.ts',
  commands: 'packages/cli-core/src/generated/commands.ts',
};

// The parts of the contract that are not the console's API: the browser's sign-in (`console login`
// replaces it) and the in-cluster service tokens. The SDK keeps their types and operations; the CLI
// has no command for them.
const NOT_COMMANDS = [/^\/auth\//, /^\/internal\//];

// Global flags of the command core; an operation's own flag may shadow only these two.
const GLOBAL_FLAGS = new Set(['output', 'account', 'region', 'all', 'body', 'body-file', 'idempotency-key', 'help']);
const SHADOWABLE = new Set(['account', 'region']);

// Headers the client sets itself: never flags.
const CLIENT_HEADERS = new Set(['x-csrf-token', 'idempotency-key', 'authorization']);

const METHODS = ['get', 'put', 'post', 'patch', 'delete'];

// openapi-typescript parses the contract with @redocly/openapi-core; the tables are read with the
// same parser, resolved from openapi-typescript itself, so both see one document.
const { parseYaml } = createRequire(fileURLToPath(import.meta.resolve('openapi-typescript')))('@redocly/openapi-core');

/** Generates every output; answers a map of path (relative to the root) to content. */
export async function generate() {
  const source = await readFile(path.join(ROOT, CONTRACT), 'utf8');
  const sha256 = createHash('sha256').update(source).digest('hex');
  const doc = parseYaml(source);
  const banner = `// Generated by scripts/generate.mjs from ${CONTRACT} (sha256 ${sha256}).\n// Do not edit: change the pinned contract and run \`npm run generate\`.\n`;

  const ast = await openapiTS(pathToFileURL(path.join(ROOT, CONTRACT)), { silent: true });
  const types = banner + '\n' + astToString(ast);

  const ops = readOperations(doc);
  return new Map([
    [OUTPUTS.types, types],
    [OUTPUTS.operations, banner + '\n' + operationsModule(ops)],
    [OUTPUTS.commands, banner + '\n' + commandsModule(doc, ops)],
  ]);
}

// ---------------------------------------------------------------------------------------------
// Reading the contract

function deref(doc, node, seen = new Set()) {
  if (!node || typeof node !== 'object' || typeof node.$ref !== 'string') return node;
  const ref = node.$ref;
  if (!ref.startsWith('#/')) throw new Error(`only local references are supported: ${ref}`);
  if (seen.has(ref)) throw new Error(`circular reference: ${ref}`);
  seen.add(ref);
  let target = doc;
  for (const part of ref.slice(2).split('/')) {
    target = target?.[part.replace(/~1/g, '/').replace(/~0/g, '~')];
  }
  if (target === undefined) throw new Error(`unresolved reference: ${ref}`);
  return deref(doc, target, seen);
}

function schemaType(doc, schema) {
  const s = deref(doc, schema) ?? {};
  if (Array.isArray(s.allOf) && s.allOf.length > 0) return schemaType(doc, s.allOf[0]);
  let type = s.type;
  if (Array.isArray(type)) type = type.find((t) => t !== 'null');
  if (type === 'array') {
    const items = schemaType(doc, s.items);
    return { type: items.type, array: true, enum: items.enum };
  }
  const values = Array.isArray(s.enum) ? s.enum.filter((v) => v !== null).map(String) : undefined;
  return { type: type ?? 'string', array: false, enum: values, default: s.default };
}

function readParameters(doc, pathItem, op) {
  const byKey = new Map();
  for (const raw of [...(pathItem.parameters ?? []), ...(op.parameters ?? [])]) {
    const p = deref(doc, raw);
    byKey.set(`${p.in}:${p.name}`, p);
  }
  const params = [];
  for (const p of byKey.values()) {
    if (p.in === 'cookie') continue;
    const t = schemaType(doc, p.schema);
    params.push({
      name: p.name,
      in: p.in,
      required: p.in === 'path' ? true : Boolean(p.required),
      type: t.type,
      array: t.array,
      enum: t.enum,
      default: t.default,
      namePattern: p['x-name-pattern'],
      description: p.description ?? deref(doc, p.schema)?.description,
    });
  }
  return params;
}

function successResponses(doc, op) {
  return Object.entries(op.responses ?? {})
    .filter(([code]) => /^2(\d\d|XX)$/i.test(code))
    .map(([code, r]) => ({ code, response: deref(doc, r) }));
}

function isPaged(doc, op, params) {
  if (!params.some((p) => p.in === 'query' && p.name === 'after')) return false;
  const ok = successResponses(doc, op).find((r) => r.code === '200');
  let schema = deref(doc, ok?.response?.content?.['application/json']?.schema);
  if (schema?.allOf) schema = Object.assign({}, ...schema.allOf.map((s) => deref(doc, s)));
  const props = schema?.properties ?? {};
  return deref(doc, props.items)?.type === 'array' && 'next' in props;
}

function responseKind(doc, op) {
  const types = successResponses(doc, op).flatMap((r) => Object.keys(r.response?.content ?? {}));
  if (types.includes('text/event-stream')) return 'events';
  if (types.some((t) => t === 'application/json' || t.endsWith('+json'))) return 'json';
  if (types.length > 0) return 'text';
  return 'none';
}

function readOperations(doc) {
  const ops = [];
  const ids = new Set();
  for (const [p, item] of Object.entries(doc.paths ?? {})) {
    for (const method of METHODS) {
      const op = item[method];
      if (!op) continue;
      if (!op.operationId) throw new Error(`${method.toUpperCase()} ${p} has no operationId`);
      if (ids.has(op.operationId)) throw new Error(`operationId ${op.operationId} is used twice`);
      ids.add(op.operationId);
      const params = readParameters(doc, item, op);
      const rb = deref(doc, op.requestBody);
      const contentTypes = Object.keys(rb?.content ?? {});
      const schemaRef = rb?.content?.[contentTypes[0]]?.schema?.$ref;
      ops.push({
        operationId: op.operationId,
        method: method.toUpperCase(),
        path: p,
        tags: op.tags ?? [],
        summary: op.summary,
        description: op.description,
        params,
        body: rb ? { required: Boolean(rb.required), contentType: contentTypes[0], schema: schemaRef?.split('/').pop() } : undefined,
        idempotencyKey: params.some((x) => x.in === 'header' && x.name.toLowerCase() === 'idempotency-key'),
        paged: isPaged(doc, op, params),
        response: responseKind(doc, op),
      });
    }
  }
  return ops;
}

// ---------------------------------------------------------------------------------------------
// The SDK's operation table

function operationsModule(ops) {
  const table = {};
  for (const op of ops) {
    table[op.operationId] = {
      method: op.method,
      path: op.path,
      tags: op.tags,
      params: op.params.map((p) => compact({ name: p.name, in: p.in, required: p.required, array: p.array || undefined, namePattern: p.namePattern })),
      body: op.body ? { required: op.body.required, contentType: op.body.contentType } : undefined,
      idempotencyKey: op.idempotencyKey,
      paged: op.paged,
      response: op.response,
    };
  }
  const union = (pred) => {
    const names = ops.filter(pred).map((o) => `  | '${o.operationId}'`);
    return names.length ? `\n${names.join('\n')}` : ' never';
  };
  return `import type { operations } from './console-bff.js';
import type { OperationInfo } from '../operation-info.js';

/** How to call each operation of the contract. */
export const OPERATIONS: { readonly [K in keyof operations]: OperationInfo } = ${literal(table)};

/** The operations that answer \`{ items, next }\` pages and take \`after\`. */
export type PagedOperationId =${union((o) => o.paged)};

/** The operations that answer a stream of server-sent events. */
export type EventStreamOperationId =${union((o) => o.response === 'events')};
`;
}

// ---------------------------------------------------------------------------------------------
// The CLI's command table

function words(id) {
  return (id.match(/[A-Z]?[a-z0-9]+|[A-Z]+(?![a-z])/g) ?? [id]).map((w) => w.toLowerCase());
}

function kebab(name) {
  return words(name.replace(/[_\s]+/g, '-'))
    .join('-')
    .replace(/-+/g, '-');
}

function flagName(param) {
  if (param.namePattern) return param.name; // tag.<name>: the query name is the flag
  if (param.in === 'header') return param.name.toLowerCase();
  return param.name
    .split(/[_\s-]+/)
    .map((part) => words(part).join('-'))
    .join('-');
}

function stripTag(opWords, tagWords) {
  const plural = tagWords;
  const singular = [...tagWords.slice(0, -1), tagWords[tagWords.length - 1].replace(/s$/, '')];
  for (const form of [plural, singular]) {
    for (let i = 0; i + form.length <= opWords.length; i++) {
      if (form.every((w, j) => opWords[i + j] === w)) {
        return [...opWords.slice(0, i), ...opWords.slice(i + form.length)];
      }
    }
  }
  return opWords;
}

/** `listResources` under Resources is `list`; `explainJobFailure` under Jobs is `explain-failure`. */
export function commandName(operationId, tag) {
  const opWords = words(operationId);
  const tagWords = tag.split(/[\s_-]+/).map((w) => w.toLowerCase());
  const rest = stripTag(opWords, tagWords);
  // `search` under Search: the group's own command, run as `console search --q …`
  if (rest.length === 0) return { name: opWords.join('-'), groupDefault: true };
  return { name: rest.join('-'), groupDefault: false };
}

function commandsModule(doc, ops) {
  const tagInfo = new Map((doc.tags ?? []).map((t) => [t.name, t]));
  const groups = new Map();
  for (const op of ops) {
    if (NOT_COMMANDS.some((re) => re.test(op.path))) continue;
    const tag = op.tags[0] ?? 'Other';
    const groupName = kebab(tag);
    if (!groups.has(groupName)) {
      groups.set(groupName, { name: groupName, tag, description: tagInfo.get(tag)?.description, commands: [] });
    }
    const group = groups.get(groupName);
    const { name, groupDefault } = commandName(op.operationId, tag);
    if (group.commands.some((c) => c.name === name)) {
      throw new Error(`${op.operationId} and another operation are both \`${groupName} ${name}\``);
    }
    const positionals = [...op.path.matchAll(/\{([^}]+)\}/g)].map((m) => m[1]);
    const flags = [];
    for (const p of op.params) {
      if (p.in === 'header' && CLIENT_HEADERS.has(p.name.toLowerCase())) continue;
      const flag = flagName(p);
      if (flags.some((f) => f.flag === flag)) throw new Error(`${op.operationId}: two parameters are --${flag}`);
      if (GLOBAL_FLAGS.has(flag) && !SHADOWABLE.has(flag)) throw new Error(`${op.operationId}: --${flag} is a global flag`);
      flags.push(
        compact({
          flag,
          name: p.name,
          in: p.in,
          required: p.required || undefined,
          type: p.type,
          array: p.array || undefined,
          enum: p.enum,
          default: p.default,
          namePattern: p.namePattern,
          description: p.description,
        }),
      );
    }
    // the path's own order, then the rest as the contract lists them
    flags.sort((a, b) => order(a, positionals) - order(b, positionals));
    group.commands.push(
      compact({
        name,
        groupDefault: groupDefault || undefined,
        operationId: op.operationId,
        method: op.method,
        path: op.path,
        summary: op.summary,
        description: op.description,
        positionals,
        flags,
        body: op.body,
        paged: op.paged || undefined,
        response: op.response,
      }),
    );
  }
  const sorted = [...groups.values()].sort((a, b) => a.name.localeCompare(b.name));
  for (const g of sorted) g.commands.sort((a, b) => a.name.localeCompare(b.name));
  return `import type { GroupSpec } from '../spec.js';

/** One group per tag of the contract, one command per operation. */
export const GROUPS: readonly GroupSpec[] = ${literal(sorted.map(compact))};
`;
}

function order(flag, positionals) {
  const i = positionals.indexOf(flag.name);
  return flag.in === 'path' && i >= 0 ? i - 1000 : 0;
}

// ---------------------------------------------------------------------------------------------
// Writing

function compact(obj) {
  return Object.fromEntries(Object.entries(obj).filter(([, v]) => v !== undefined));
}

/** A TypeScript literal: JSON with identifier keys left bare, short values on one line. */
function literal(value, indent = '') {
  const flat = flatLiteral(value);
  if (flat !== undefined && indent.length + flat.length <= 100) return flat;
  const next = indent + '  ';
  if (Array.isArray(value)) {
    return `[\n${value.map((v) => next + literal(v, next)).join(',\n')},\n${indent}]`;
  }
  if (value && typeof value === 'object') {
    const entries = Object.entries(value).filter(([, v]) => v !== undefined);
    return `{\n${entries.map(([k, v]) => `${next}${key(k)}: ${literal(v, next)}`).join(',\n')},\n${indent}}`;
  }
  return JSON.stringify(value);
}

function flatLiteral(value) {
  if (Array.isArray(value)) {
    const parts = value.map(flatLiteral);
    return parts.includes(undefined) ? undefined : `[${parts.join(', ')}]`;
  }
  if (value && typeof value === 'object') {
    const entries = Object.entries(value).filter(([, v]) => v !== undefined);
    if (entries.length === 0) return '{}';
    const parts = entries.map(([k, v]) => {
      const inner = flatLiteral(v);
      return inner === undefined ? undefined : `${key(k)}: ${inner}`;
    });
    return parts.includes(undefined) ? undefined : `{ ${parts.join(', ')} }`;
  }
  return JSON.stringify(value);
}

function key(k) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) ? k : JSON.stringify(k);
}

async function main(argv) {
  const check = argv.includes('--check');
  const outputs = await generate();
  const stale = [];
  for (const [file, content] of outputs) {
    const target = path.join(ROOT, file);
    const current = await readFile(target, 'utf8').catch(() => undefined);
    if (current === content) continue;
    if (check) {
      stale.push(file);
    } else {
      await mkdir(path.dirname(target), { recursive: true });
      await writeFile(target, content);
      console.log(`wrote ${file}`);
    }
  }
  if (check && stale.length > 0) {
    console.error(`The generated files are not those of ${CONTRACT}; run \`npm run generate\` and commit:\n  ${stale.join('\n  ')}`);
    process.exitCode = 1;
  } else if (check) {
    console.log(`The generated files are current with ${CONTRACT}.`);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main(process.argv.slice(2));
}
