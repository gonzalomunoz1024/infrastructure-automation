-- What the wizard's Test connection and Try it calls proved, per provider name (ReviewEvidencePort),
-- for the Review step and the publish to judge: one row per connection test (kind connection,
-- doc a ConnectionTest) or try (kind try, doc an ActionTry), read back in the order they were
-- recorded (id). The bounds are the in-memory store's: a write deletes the oldest rows beyond
-- the last 50 connection tests and the last 500 tries of a provider, and a response over 256 KiB
-- is kept without its body. A row holds endpoints, credential references and responses, never a
-- credential value.
CREATE TABLE review_evidence (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider  VARCHAR(200) NOT NULL,
    kind      VARCHAR(20)  NOT NULL,
    at        TIMESTAMP WITH TIME ZONE,
    doc       TEXT         NOT NULL
);
CREATE INDEX review_evidence_provider ON review_evidence (provider, kind, id);
